-- Oil is measured in litres, not the integer "each" unit used by parts.
-- Keep its physical stock and movement history separate from integer parts.
CREATE TABLE IF NOT EXISTS workshop_oils (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dealer_id integer NOT NULL,
  name text NOT NULL,
  grade text NOT NULL DEFAULT '',
  specification text NOT NULL DEFAULT '',
  brand text NOT NULL DEFAULT '',
  purchase_cost_per_litre numeric(15,2) NOT NULL DEFAULT 0 CONSTRAINT workshop_oils_purchase_ck CHECK (purchase_cost_per_litre >= 0),
  selling_price_per_litre numeric(15,2) NOT NULL DEFAULT 0 CONSTRAINT workshop_oils_selling_ck CHECK (selling_price_per_litre >= 0),
  stock_litres numeric(15,3) NOT NULL DEFAULT 0 CONSTRAINT workshop_oils_stock_ck CHECK (stock_litres >= 0),
  reorder_litres numeric(15,3) NOT NULL DEFAULT 0 CONSTRAINT workshop_oils_reorder_ck CHECK (reorder_litres >= 0),
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS workshop_oils_dealer_idx ON workshop_oils(dealer_id, name);
CREATE TABLE IF NOT EXISTS workshop_oil_requests (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dealer_id integer NOT NULL,
  job_card_id integer NOT NULL REFERENCES job_cards(id),
  oil_id integer NOT NULL REFERENCES workshop_oils(id),
  requested_litres numeric(15,3) NOT NULL,
  issued_litres numeric(15,3) NOT NULL DEFAULT 0,
  returned_litres numeric(15,3) NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'requested',
  name_snapshot text NOT NULL,
  unit_price_per_litre numeric(15,2) NOT NULL,
  requested_by integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT workshop_oil_requests_positive_ck CHECK (requested_litres > 0 AND issued_litres >= 0 AND issued_litres <= requested_litres AND returned_litres >= 0 AND returned_litres <= issued_litres),
  CONSTRAINT workshop_oil_requests_status_ck CHECK (status IN ('requested','approved','partial','issued','cancelled'))
);
CREATE INDEX IF NOT EXISTS workshop_oil_requests_job_idx ON workshop_oil_requests(dealer_id, job_card_id);
CREATE INDEX IF NOT EXISTS workshop_oil_requests_oil_idx ON workshop_oil_requests(dealer_id, oil_id);
CREATE TABLE IF NOT EXISTS workshop_oil_movements (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dealer_id integer NOT NULL,
  oil_id integer NOT NULL REFERENCES workshop_oils(id),
  request_id integer REFERENCES workshop_oil_requests(id),
  delta_litres numeric(15,3) NOT NULL CONSTRAINT workshop_oil_movements_delta_ck CHECK (delta_litres <> 0),
  reason text NOT NULL CONSTRAINT workshop_oil_movements_reason_ck CHECK (reason IN ('opening','adjustment','issue','return')),
  actor_id integer,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS workshop_oil_movements_oil_idx ON workshop_oil_movements(dealer_id, oil_id, created_at);
CREATE TABLE IF NOT EXISTS workshop_invoice_oils (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dealer_id integer NOT NULL,
  invoice_id integer NOT NULL REFERENCES service_invoices(id),
  request_id integer NOT NULL REFERENCES workshop_oil_requests(id),
  name_snapshot text NOT NULL,
  quantity_litres numeric(15,3) NOT NULL CONSTRAINT workshop_invoice_oils_quantity_ck CHECK (quantity_litres > 0),
  unit_price_per_litre numeric(15,2) NOT NULL,
  amount numeric(15,2) NOT NULL,
  CONSTRAINT workshop_invoice_oils_dealer_request_uq UNIQUE (dealer_id, request_id)
);
CREATE INDEX IF NOT EXISTS workshop_invoice_oils_invoice_idx ON workshop_invoice_oils(dealer_id, invoice_id);